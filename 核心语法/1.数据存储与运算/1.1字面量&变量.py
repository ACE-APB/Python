# 1.字面量/常量

# 指程序中，直接书写的固定值（数据）
#
# 例如：18；8.5；"Python"
#
# 书写格式/类型：
#   1.整数（int）：10
#   2.浮点数/小数（float）：8.5
#   3.布尔（bool）：True(1)/False(0)
#   4.字符串（str）："Python"
#   5.空值（NoneType）：None
#   6.数据容器：列表/元组/集合/字典...

print(100)
print(3.14)
print(True)
print(False)
print(True + 1)
print(False - 1)
print("hello world")
print(None)

# 2.变量

# 指程序中用来存储单个数据的容器，而且经常发生变化
# 定义格式：变量名 = 变量的值
num = 114514
print(num)
num += 1
print(num)
num = "OK"
print(num)
a, b = 91, 78
print(a, b)